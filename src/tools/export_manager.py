def export_txt(p: ExportPayload) -> bytes:
    """Plain text export — clean, no markdown symbols."""
    lines = [
        "=" * 60,
        f"CATERYA REPORT — {p.title}",
        "=" * 60,
        f"Exported   : {_now_str()}",
        f"Agent      : {p.agent_id}",
        f"Ethics     : {p.ethics_verdict.upper()}",
        f"Duration   : {p.duration_ms:.0f}ms",
        "",
        "-" * 60,
        "TASK",
        "-" * 60,
        p.task,
        "",
        "-" * 60,
        "OUTPUT",
        "-" * 60,
        _strip_md(p.content),
        "",
    ]

    if p.steps:
        lines += ["-" * 60, "PIPELINE STEPS", "-" * 60, ""]
        for i, step in enumerate(p.steps, 1):
            lines += [
                f"Step {i}: {step.get('agent','').replace('_',' ').title()}",
                "-" * 30,
                _strip_md(step.get("output", "") or step.get("result", "")),
                "",
            ]

    if p.metadata:
        lines += ["-" * 60, "METADATA", "-" * 60]
        for k, v in p.metadata.items():
            lines.append(f"{k}: {v}")
        lines.append("")

    lines += ["=" * 60, "© 2026 Caterya Tech — aryhharyanto@proton.me", "=" * 60]
    return "\n".join(lines).encode("utf-8")


