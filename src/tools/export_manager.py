EXPORT_FORMATS = {
    "PDF (.pdf)":       ("pdf",      "application/pdf",                                              ".pdf"),
    "Excel (.xlsx)":    ("xlsx",     "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", ".xlsx"),
    "JSON (.json)":     ("json",     "application/json",                                             ".json"),
    "Markdown (.md)":   ("markdown", "text/markdown",                                                ".md"),
    "CSV (.csv)":       ("csv",      "text/csv",                                                     ".csv"),
    "Plain Text (.txt)": ("txt",     "text/plain",                                                   ".txt"),
}


def export(payload: ExportPayload, fmt: str, title: str = "") -> tuple[bytes, str, str]:
    """
    Export payload in given format.
    Returns (bytes, mime_type, filename).
    fmt: 'pdf' | 'xlsx' | 'json' | 'markdown' | 'md' | 'csv' | 'txt'
    """
    if title:
        payload.title = title

    slug = _slug(payload.title or payload.agent_id)
    ts = datetime.now().strftime("%Y%m%d_%H%M")

    # Adapt old-style dict result to ExportPayload if needed
    if isinstance(payload, dict):
        payload = ExportPayload.from_result(payload)

    # Build result dict for inner functions
    result = {
        "agent_id": payload.agent_id,
        "task": payload.task,
        "result": payload.content,
        "final_output": payload.content,
        "ethics_verdict": payload.ethics_verdict,
        "duration_ms": payload.duration_ms,
        "steps": payload.steps,
        "metadata": payload.metadata,
        "success": payload.success,
        "timestamp": payload.timestamp,
    }

    fmt = fmt.lower().replace(".", "")
    if fmt == "pdf":
        return export_pdf(result, payload.title), "application/pdf", f"caterya_{slug}_{ts}.pdf"
    elif fmt == "xlsx":
        return export_excel(result, payload.title), "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", f"caterya_{slug}_{ts}.xlsx"
    elif fmt == "json":
        return export_json(result), "application/json", f"caterya_{slug}_{ts}.json"
    elif fmt in ("markdown", "md"):
        return export_markdown(result, payload.title), "text/markdown", f"caterya_{slug}_{ts}.md"
    elif fmt == "csv":
        return export_csv(result), "text/csv", f"caterya_{slug}_{ts}.csv"
    elif fmt == "txt":
        return export_txt(payload), "text/plain", f"caterya_{slug}_{ts}.txt"
    else:
        raise ValueError(f"Unknown export format: {fmt}")
